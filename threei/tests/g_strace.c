int main(int argc, char **argv) {
    assert(argc >= 2);
    int me = getpid();
    pid_t pid = fork();
    assert(pid >= 0);
    if (pid == 0) {
        int c = getpid();
        for (int n = 0; n < NCALLS; n++)
            if (handlers[n])
                assert(register_handler(c, n, me, (uint64_t)(uintptr_t)handlers[n]) == 0);
        execv(argv[1], &argv[1]);
        _exit(127);
    }
    int st;
    wait(&st);
    return WIFEXITED(st) ? WEXITSTATUS(st) : 128 + WTERMSIG(st);
}
