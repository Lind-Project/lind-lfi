static int trace(int nr, uint64_t c1, const uint64_t a[6], const uint64_t ac[6]) {
    int me = getpid();
    int r = make_threei_call(nr, 0, me, c1, a[0], ac[0], a[1], ac[1], a[2], ac[2],
                             a[3], ac[3], a[4], ac[4], a[5], ac[5], 0);
    // Don't trace our own output (write to fd 2 by this grate is a separate
    // cage's call); the traced cage's writes are shown like any other call.
    char line[160];
    const char *name = names[nr];
    int n;
    if (name)
        n = snprintf(line, sizeof line, "[strace cage %llu] %s(0x%llx, 0x%llx, 0x%llx) = %d\n",
                     (unsigned long long)c1, name, (unsigned long long)a[0],
                     (unsigned long long)a[1], (unsigned long long)a[2], r);
    else
        n = snprintf(line, sizeof line, "[strace cage %llu] syscall_%d(0x%llx, 0x%llx, 0x%llx) = %d\n",
                     (unsigned long long)c1, nr, (unsigned long long)a[0],
                     (unsigned long long)a[1], (unsigned long long)a[2], r);
    write(2, line, n);
    return r;
}

